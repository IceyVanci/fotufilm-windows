/// The Chinese for [english], or [english] itself when there is no translation yet.
String t(String english) => zhStrings[english] ?? english;

const Set<String> _translatedFields = <String>{'title', 'label', 'name', 'detail', 'hint'};

/// Translates the catalogue's display fields in place, leaving every key, id and machine token
/// (availability, field, group, dynamicMenu) as the engine reads it.
Object? localizeCatalogueValue(Object? value) {
  if (value is List) return value.map(localizeCatalogueValue).toList();
  if (value is Map) {
    final out = <String, Object?>{};
    for (final entry in value.entries) {
      final key = entry.key as String;
      final child = entry.value;
      if (_translatedFields.contains(key) && child is String) {
        out[key] = t(child);
      } else {
        out[key] = localizeCatalogueValue(child);
      }
    }
    return out;
  }
  return value;
}
